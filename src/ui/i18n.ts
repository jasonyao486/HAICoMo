export function translator(locale: Settings["locale"]) {
  const dictionary = dictionaries[locale];
  return (key: Key) => dictionary[key];
}
export type Translate = ReturnType<typeof translator>;
export function formatDate(value: string, locale: string) {
  return value
    ? new Intl.DateTimeFormat(locale, {
        month: "short",
        day: "numeric",
      }).format(new Date(value.length === 10 ? value + "T12:00:00" : value))
    : "—";
}
export function formatDuration(ms: number, t: (key: Key) => string) {
  if (!(ms > 0)) return "—";
  const seconds = Math.round(ms / 1000), h = Math.floor(seconds / 3600), m = Math.floor((seconds % 3600) / 60), sec = seconds % 60;
  const parts = [h ? `${h} ${t("unitHour")}` : "", m ? `${m} ${t("unitMinute")}` : "", !h && (sec || !m) ? `${sec} ${t("unitSecond")}` : ""].filter(Boolean);
  return parts.join(" ");
}
